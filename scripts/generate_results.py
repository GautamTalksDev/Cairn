#!/usr/bin/env python3
"""Regenerate RESULTS.md from runnable experiments (do not hand-edit RESULTS.md).

Default sequence: full ``data/processed/anymal_1_1_compslam`` when present,
else synthetic ``examples/quickstart`` from ``scripts/make_quickstart_data.py``.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from cairn._internal.detectors.consistency import SolutionSeparationDetector
from cairn.types import Pose, PoseEstimate


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _load_script(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def _eval_solution_separation(
    *,
    p_fa: float = 0.05,
    n_trials: int = 2000,
    seed: int | None = None,
) -> dict[str, object]:
    if seed is None:
        seed = int(os.environ.get("CAIRN_RNG_SEED", "0"))
    rng = np.random.default_rng(seed)
    detector = SolutionSeparationDetector(p_fa=p_fa)
    truth = np.array([1.0, -2.0, 0.5])
    stds = {"a": 0.05, "b": 0.06, "c": 0.04, "d": 0.07}

    def make_est(name: str, pos: np.ndarray, std: float) -> PoseEstimate:
        cov = np.diag([std**2, std**2, std**2, 0.01, 0.01, 0.01])
        return PoseEstimate(
            pose=Pose(
                timestamp=0.0,
                position=pos,
                orientation=np.array([1.0, 0.0, 0.0, 0.0]),
            ),
            covariance=cov,
            source=name,
        )

    false_alarms = 0
    for _ in range(n_trials):
        sources = {
            name: make_est(name, truth + rng.normal(scale=std, size=3), std)
            for name, std in stds.items()
        }
        if detector.detect(sources).faulted_source is not None:
            false_alarms += 1

    biased = {
        "vio": make_est("vio", truth + np.array([0.01, -0.02, 0.0]), 0.04),
        "lidar": make_est("lidar", truth + np.array([1.0, 0.0, 0.0]), 0.04),
        "imu_prop": make_est("imu_prop", truth + np.array([-0.02, 0.01, 0.0]), 0.06),
    }
    isolated = detector.detect(biased).faulted_source
    return {
        "p_fa_configured": p_fa,
        "n_trials": n_trials,
        "empirical_far": false_alarms / n_trials,
        "injected_fault_isolated": isolated == "lidar",
        "isolated_source": isolated,
    }


def render_results_md(traj: dict[str, object], ss: dict[str, object]) -> str:
    naive = traj["naive"]  # type: ignore[index]
    deg = traj["degeneracy"]  # type: ignore[index]
    assert isinstance(naive, dict) and isinstance(deg, dict)
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    delta_pp = 100.0 * (float(deg["missed_detection_rate"]) - float(naive["missed_detection_rate"]))
    return "\n".join(
        [
            "# Cairn results",
            "",
            f"_Auto-generated by `scripts/generate_results.py` on {now}. "
            "Do not hand-edit._",
            "",
            "## Trajectory integrity (bundled quickstart)",
            "",
            f"- Sequence: `{traj['sequence']}`",
            f"- Alignment: `{traj['align_mode']}`",
            f"- Claimed filter σ_xy / σ_z: "
            f"`{traj['claimed_std_xy_m']}` / `{traj['claimed_std_z_m']}` m",
            f"- ATE RMSE: **{float(traj['ate_rmse_m']):.4f} m**",
            f"- Corridor-like epochs: "
            f"**{100.0 * float(traj['fraction_corridor_epochs']):.1f}%**",
            "",
            "| Method | Missed-detection rate | False-alarm rate | Availability |",
            "| --- | ---: | ---: | ---: |",
            (
                f"| Naive self-reported covariance (CP-7) | "
                f"{100.0 * float(naive['missed_detection_rate']):.2f}% | "
                f"{100.0 * float(naive['false_alarm_rate']):.2f}% | "
                f"{100.0 * float(naive['availability']):.2f}% |"
            ),
            (
                f"| Degeneracy-aware PL inflation (CP-8) | "
                f"{100.0 * float(deg['missed_detection_rate']):.2f}% | "
                f"{100.0 * float(deg['false_alarm_rate']):.2f}% | "
                f"{100.0 * float(deg['availability']):.2f}% |"
            ),
            "",
            f"**Headline delta:** missed-detection rate changes by "
            f"**{delta_pp:+.2f} percentage points** versus naive covariance.",
            "",
            "## Solution separation (CP-9)",
            "",
            "Position-only WLS solution-separation on synthetic independent sources "
            "(Monte Carlo under H0 + one injected-bias trial).",
            "",
            "| Check | Result |",
            "| --- | --- |",
            f"| Configured family-wise P_FA | {float(ss['p_fa_configured']):.3f} |",
            f"| Trials | {ss['n_trials']} |",
            f"| Empirical false-alarm rate | {100.0 * float(ss['empirical_far']):.2f}% |",
            (
                f"| Injected lidar bias isolated | "
                f"{'yes' if ss['injected_fault_isolated'] else 'no'} "
                f"(`{ss['isolated_source']}`) |"
            ),
            "",
            "## Reproduce",
            "",
            "```bash",
            "python -m venv .venv && source .venv/bin/activate",
            'pip install -e ".[dev]"',
            "python scripts/generate_results.py",
            "cairn score \\",
            "  --est examples/quickstart/est.tum \\",
            "  --gt examples/quickstart/gt.tum \\",
            "  --reports examples/quickstart/reports.txt \\",
            "  --alert-limit 2.0 \\",
            "  --out outputs/quickstart",
            "```",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sequence-dir",
        type=Path,
        default=root / "examples" / "quickstart",
    )
    parser.add_argument("--out", type=Path, default=root / "RESULTS.md")
    args = parser.parse_args(argv)

    run_deg = _load_script("cairn_run_degeneracy", root / "scripts" / "run_degeneracy.py")
    raw = run_deg.run_comparison(args.sequence_dir)
    traj = {
        "sequence": raw["sequence"],
        "align_mode": raw["align_mode"],
        "claimed_std_xy_m": raw["claimed_std_xy_m"],
        "claimed_std_z_m": raw["claimed_std_z_m"],
        "ate_rmse_m": raw["ate_rmse_m"],
        "fraction_corridor_epochs": raw["fraction_corridor_epochs"],
        "naive": raw["naive"],
        "degeneracy": raw["degeneracy"],
    }
    ss = _eval_solution_separation()
    text = render_results_md(traj, ss)
    args.out.write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
