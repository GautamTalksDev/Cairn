#!/usr/bin/env python3
"""Generate redistributable synthetic trajectories for ``examples/quickstart/``.

CERBERUS and other InC-NC datasets must not be bundled. This script builds a
plausible underground corridor path (~700 poses at 10 Hz), two noisy pose
sources, an injected along-track drift segment so consistency monitoring
demonstrates a detection, and matching integrity reports.

Outputs (overwrite):

* ``examples/quickstart/gt.tum``
* ``examples/quickstart/est.tum``
* ``examples/quickstart/reports.txt``
* ``examples/quickstart/README.md`` (short provenance note)

Every file header states the data is synthetic. Re-run with a fixed seed for
bit-stable regeneration::

    python scripts/make_quickstart_data.py --seed 0
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np

from cairn import CairnConfig, CairnMonitor, Pose, PoseEstimate
from cairn._internal.io.reports import save_integrity_reports
from cairn.config import MonitorSection
from cairn.types import Trajectory

_TUM_HEADER = (
    "# SYNTHETIC DATA generated by scripts/make_quickstart_data.py\n"
    "# Not CERBERUS / not field-recorded. Freely redistributable with this repository.\n"
    "# Units: timestamp seconds; position metres; quaternion TUM w-last (qx qy qz qw).\n"
    "# Frame: map (shared navigation frame for both sources).\n"
)

_REPORTS_HEADER = (
    "# SYNTHETIC DATA generated by scripts/make_quickstart_data.py\n"
    "# Not CERBERUS / not field-recorded. Freely redistributable with this repository.\n"
    "# Units: timestamp seconds; protection levels metres; state nominal|degraded|do_not_trust.\n"
    "# Produced by CairnMonitor(consistency) on synthetic lidar (est) vs vio.\n"
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _yaw_quat_wxyz(yaw_rad: float) -> np.ndarray:
    """Body→map rotation about +z; Cairn stores w-first."""
    half = 0.5 * float(yaw_rad)
    return np.array([math.cos(half), 0.0, 0.0, math.sin(half)], dtype=np.float64)


def _wxyz_to_tum_line(ts: float, xyz: np.ndarray, q_wxyz: np.ndarray) -> str:
    w, x, y, z = (float(v) for v in q_wxyz)
    tx, ty, tz = (float(v) for v in xyz)
    return (
        f"{ts:.9f} {tx:.9f} {ty:.9f} {tz:.9f} "
        f"{x:.9f} {y:.9f} {z:.9f} {w:.9f}"
    )


def _corridor_path(
    n: int,
    dt_s: float,
    *,
    speed_m_s: float = 0.8,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Piecewise corridor with right-angle turns; returns t, xyz (N,3), yaw (N,)."""
    # Segment lengths (metres) along a rectangular-ish tunnel loop stub.
    segments = [
        (25.0, 0.0),  # +x
        (0.0, 12.0),  # +y turn
        (18.0, 0.0),  # +x
        (0.0, -10.0),  # -y
        (22.0, 0.0),  # +x
        (0.0, 8.0),  # +y
        (15.0, 0.0),  # +x
    ]
    waypoints = [(0.0, 0.0)]
    x = y = 0.0
    for dx, dy in segments:
        x += dx
        y += dy
        waypoints.append((x, y))

    # Arc-length parametrization of the polyline.
    pts = np.asarray(waypoints, dtype=np.float64)
    seg_vec = np.diff(pts, axis=0)
    seg_len = np.linalg.norm(seg_vec, axis=1)
    cum = np.concatenate([[0.0], np.cumsum(seg_len)])
    total = float(cum[-1])
    duration = (n - 1) * dt_s
    # Constant speed along the polyline (may not finish the full polyline).
    dist = np.minimum(np.arange(n, dtype=np.float64) * speed_m_s * dt_s, total - 1e-9)

    xyz = np.zeros((n, 3), dtype=np.float64)
    yaw = np.zeros(n, dtype=np.float64)
    for i, s in enumerate(dist):
        j = int(np.searchsorted(cum, s, side="right") - 1)
        j = min(max(j, 0), len(seg_len) - 1)
        local = (s - cum[j]) / max(seg_len[j], 1e-12)
        p0 = pts[j]
        p1 = pts[j + 1]
        xy = p0 + local * (p1 - p0)
        xyz[i, 0] = xy[0]
        xyz[i, 1] = xy[1]
        # Gentle vertical undulation (metres).
        xyz[i, 2] = 0.15 * math.sin(2.0 * math.pi * s / max(total, 1.0))
        yaw[i] = math.atan2(p1[1] - p0[1], p1[0] - p0[0])

    t = np.arange(n, dtype=np.float64) * dt_s
    _ = duration  # documented intent: ~70 s at defaults
    return t, xyz, yaw


def _along_track_unit(yaw_rad: float) -> np.ndarray:
    return np.array([math.cos(yaw_rad), math.sin(yaw_rad), 0.0], dtype=np.float64)


def _build_estimates(
    t: np.ndarray,
    xyz: np.ndarray,
    yaw: np.ndarray,
    *,
    cov: np.ndarray,
    source: str,
    noise_xy_m: float,
    noise_z_m: float,
    noise_yaw_rad: float,
    rng: np.random.Generator,
    drift_start_frac: float,
    drift_rate_m_s: float,
) -> list[PoseEstimate]:
    n = len(t)
    onset_i = int(drift_start_frac * (n - 1))
    estimates: list[PoseEstimate] = []
    for i in range(n):
        pos = xyz[i].copy()
        pos[0] += float(rng.normal(0.0, noise_xy_m))
        pos[1] += float(rng.normal(0.0, noise_xy_m))
        pos[2] += float(rng.normal(0.0, noise_z_m))
        yaw_i = float(yaw[i] + rng.normal(0.0, noise_yaw_rad))
        if i >= onset_i:
            age = float(t[i] - t[onset_i])
            pos = pos + drift_rate_m_s * age * _along_track_unit(yaw[i])
        pose = Pose(
            timestamp=float(t[i]),
            position=pos,
            orientation=_yaw_quat_wxyz(yaw_i),
            frame="map",
        )
        estimates.append(PoseEstimate(pose=pose, covariance=cov.copy(), source=source))
    return estimates


def _write_tum(path: Path, estimates: list[PoseEstimate]) -> None:
    lines = [
        _TUM_HEADER.rstrip("\n"),
        "# timestamp tx ty tz qx qy qz qw",
    ]
    for est in estimates:
        lines.append(
            _wxyz_to_tum_line(
                float(est.pose.timestamp),
                est.pose.position,
                est.pose.orientation,
            )
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _cov_diag(std_xy_m: float, std_z_m: float, std_rot_rad: float) -> np.ndarray:
    return np.diag(
        [
            std_xy_m**2,
            std_xy_m**2,
            std_z_m**2,
            std_rot_rad**2,
            std_rot_rad**2,
            std_rot_rad**2,
        ]
    )


def generate(
    out_dir: Path,
    *,
    seed: int = 0,
    n_poses: int = 700,
    rate_hz: float = 10.0,
    drift_start_frac: float = 0.40,
    drift_rate_m_s: float = 0.05,
) -> dict[str, object]:
    rng = np.random.default_rng(seed)
    dt = 1.0 / rate_hz
    t, xyz, yaw = _corridor_path(n_poses, dt)

    cov_lidar = _cov_diag(0.05, 0.05, 0.04)
    cov_vio = _cov_diag(0.06, 0.06, 0.05)

    # Ground truth: clean corridor (no noise).
    gt = [
        PoseEstimate(
            pose=Pose(
                timestamp=float(t[i]),
                position=xyz[i].copy(),
                orientation=_yaw_quat_wxyz(float(yaw[i])),
                frame="map",
            ),
            covariance=cov_lidar.copy(),
            source="gt",
        )
        for i in range(n_poses)
    ]

    # Estimate / "lidar": noise + along-track drift after onset.
    est = _build_estimates(
        t,
        xyz,
        yaw,
        cov=cov_lidar,
        source="lidar",
        noise_xy_m=0.03,
        noise_z_m=0.02,
        noise_yaw_rad=0.01,
        rng=rng,
        drift_start_frac=drift_start_frac,
        drift_rate_m_s=drift_rate_m_s,
    )

    # Independent second source for the monitor: noisy, no drift.
    vio = _build_estimates(
        t,
        xyz,
        yaw,
        cov=cov_vio,
        source="vio",
        noise_xy_m=0.04,
        noise_z_m=0.03,
        noise_yaw_rad=0.015,
        rng=rng,
        drift_start_frac=1.1,  # never (past end)
        drift_rate_m_s=0.0,
    )

    cfg = CairnConfig(monitor=MonitorSection(mode="consistency"))
    reports = []
    with CairnMonitor(cfg) as mon:
        for a, b in zip(est, vio, strict=True):
            reports.append(
                mon.update(
                    float(a.pose.timestamp),
                    {a.source: a, b.source: b},
                )
            )

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_tum(out_dir / "gt.tum", gt)
    _write_tum(out_dir / "est.tum", est)

    reports_path = out_dir / "reports.txt"
    save_integrity_reports(reports, reports_path)
    # Prepend synthetic header (save_integrity_reports writes its own comment).
    body = reports_path.read_text(encoding="utf-8")
    reports_path.write_text(
        _REPORTS_HEADER + body,
        encoding="utf-8",
    )

    non_nominal = sum(1 for r in reports if r.state.value != "nominal")
    onset_t = float(t[int(drift_start_frac * (n_poses - 1))])
    readme = f"""# Quickstart sequence (synthetic)

**Synthetic data** generated by `scripts/make_quickstart_data.py` (seed={seed}).
Not CERBERUS. Not field-recorded. Freely redistributable with this repository.

| Field | Value |
| --- | --- |
| Poses | {n_poses} at {rate_hz:g} Hz (~{(n_poses - 1) / rate_hz:.0f} s) |
| Frame | `map` (shared navigation frame) |
| Path | Piecewise underground corridor with turns |
| `gt.tum` | Clean ground-truth path (metres, seconds) |
| `est.tum` | Noisy primary source + along-track drift after t≈{onset_t:.1f} s |
| `reports.txt` | Consistency-monitor reports on lidar (`est`) vs independent vio |

Regenerate::

    python scripts/make_quickstart_data.py --seed {seed}
"""
    (out_dir / "README.md").write_text(readme, encoding="utf-8")

    # Keep Trajectory construction as a sanity check.
    _ = Trajectory(gt)
    _ = Trajectory(est)

    return {
        "n_poses": n_poses,
        "rate_hz": rate_hz,
        "drift_onset_s": onset_t,
        "non_nominal_reports": non_nominal,
        "out_dir": str(out_dir),
    }


def main(argv: list[str] | None = None) -> int:
    root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=root / "examples" / "quickstart",
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--n-poses", type=int, default=700)
    parser.add_argument("--rate-hz", type=float, default=10.0)
    parser.add_argument("--drift-start-frac", type=float, default=0.40)
    parser.add_argument("--drift-rate", type=float, default=0.05, help="m/s along-track")
    args = parser.parse_args(argv)

    info = generate(
        args.out_dir,
        seed=args.seed,
        n_poses=args.n_poses,
        rate_hz=args.rate_hz,
        drift_start_frac=args.drift_start_frac,
        drift_rate_m_s=args.drift_rate,
    )
    print(
        f"wrote {info['n_poses']} poses to {info['out_dir']} "
        f"(drift onset t={info['drift_onset_s']:.1f}s; "
        f"non-nominal reports={info['non_nominal_reports']})"
    )
    if int(info["non_nominal_reports"]) < 10:
        print(
            "warning: few non-nominal reports; drift may be too mild for a demo",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
