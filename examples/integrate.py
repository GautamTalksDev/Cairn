#!/usr/bin/env python3
"""Two pose sources → Cairn integrity reports on synthetic quickstart data.

The trajectories under ``examples/quickstart/`` are **synthetic**, generated by
``scripts/make_quickstart_data.py`` (not CERBERUS). ``est.tum`` is a noisy
primary source with an injected along-track drift; ``gt.tum`` is clean ground
truth used here as a second independent stream so consistency monitoring can
demonstrate a detection after drift onset.

Units and frames:

* Timestamps: seconds
* Positions: metres in shared frame ``map``
* Orientations: Cairn uses w-first ``(w, x, y, z)``; TUM files are w-last
* Covariance: 6×6 ``[x, y, z, roll, pitch, yaw]`` in m² / rad²
* Protection levels: metres

Run from the repo root::

    python examples/integrate.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from cairn import CairnConfig, CairnMonitor, PoseEstimate
from cairn._internal.io.tum import load_tum

_HERE = Path(__file__).resolve().parent
_QUICKSTART = _HERE / "quickstart"
_EST_TUM = _QUICKSTART / "est.tum"
_GT_TUM = _QUICKSTART / "gt.tum"

_STD_XY_M = 0.05
_STD_Z_M = 0.05
_STD_ROT_RAD = 0.05


def _default_covariance() -> np.ndarray:
    """6×6 diagonal covariance: metres² for xyz, radians² for rpy."""
    return np.diag(
        [
            _STD_XY_M**2,
            _STD_XY_M**2,
            _STD_Z_M**2,
            _STD_ROT_RAD**2,
            _STD_ROT_RAD**2,
            _STD_ROT_RAD**2,
        ]
    )


def _pair_by_timestamp(
    primary: list[PoseEstimate],
    secondary: list[PoseEstimate],
    *,
    max_dt_s: float = 0.05,
) -> list[tuple[float, PoseEstimate, PoseEstimate]]:
    """Associate two streams by nearest timestamp within max_dt_s (seconds)."""
    sec_ts = np.array([e.pose.timestamp for e in secondary], dtype=np.float64)
    pairs: list[tuple[float, PoseEstimate, PoseEstimate]] = []
    used: set[int] = set()
    for a in primary:
        t = float(a.pose.timestamp)
        j = int(np.searchsorted(sec_ts, t))
        best_j = None
        best_dt = float("inf")
        for k in (j - 1, j):
            if 0 <= k < sec_ts.size and k not in used:
                dt = abs(float(sec_ts[k]) - t)
                if dt < best_dt:
                    best_dt = dt
                    best_j = k
        if best_j is not None and best_dt <= max_dt_s:
            used.add(best_j)
            pairs.append((t, a, secondary[best_j]))
    return pairs


def main() -> None:
    if not _EST_TUM.is_file() or not _GT_TUM.is_file():
        raise SystemExit(
            "missing examples/quickstart/*.tum; run:\n"
            "  python scripts/make_quickstart_data.py --seed 0"
        )

    cov = _default_covariance()
    # Synthetic est = drifted lidar; gt = clean path used as second source.
    lidar = list(
        load_tum(_EST_TUM, default_covariance=cov, source="lidar", frame="map")
    )
    vio = list(load_tum(_GT_TUM, default_covariance=cov, source="vio", frame="map"))
    epochs = _pair_by_timestamp(lidar, vio, max_dt_s=0.05)
    if not epochs:
        raise SystemExit("no timestamp matches; regenerate quickstart data")

    # Show pre-drift and post-drift windows so the detection is visible.
    demo = epochs[250:290] + epochs[400:440]
    print(
        f"integrate.py: {len(demo)} epochs from synthetic quickstart "
        f"(frame=map, units=m/s; regenerate via scripts/make_quickstart_data.py)"
    )

    with CairnMonitor(CairnConfig()) as mon:
        for t_s, est_a, est_b in demo:
            report = mon.update(
                t_s,
                {
                    est_a.source: est_a,
                    est_b.source: est_b,
                },
            )
            print(
                f"t={t_s:.1f}s  {report.state.name:12s}  "
                f"HPL={report.protection_level_horizontal:.3f}m  "
                f"VPL={report.protection_level_vertical:.3f}m  "
                f"({report.reason})"
            )


if __name__ == "__main__":
    main()
